    def build_trie(values):
        root={}
        for seq in sorted(values):
            node=root
            for cp in seq:
                node=node.setdefault(cp,{})
            node[0]=True
        nodes=[]
        edges=[]
        def flatten(node):
            node_id=len(nodes)
            nodes.append([0,0,1 if 0 in node else 0])
