def unicode_script_extensions(unicode_files, group_ranges):
    aliases={}
    codes={}
    for line in unicode_files['PropertyValueAliases.txt'].decode().splitlines():
        line=line.split('#',1)[0].strip()
        if not line: continue
        parts=[p.strip() for p in line.split(';')]
        if len(parts)<3 or parts[0]!='sc': continue
        aliases[parts[1]]=parts[2]
        codes[parts[2]]=parts[1]
    explicit={}
    for line in unicode_files['ScriptExtensions.txt'].decode().splitlines():
        line=line.split('#',1)[0].strip()
        if not line: continue
        parts=[p.strip() for p in line.split(';')]
        if len(parts)<2: continue
        rng=parts[0]
        if '..' in rng:
            first,last=rng.split('..')
        else:
            first=last=rng
        for code in parts[1].split():
            name=aliases.get(code)
            if name is None: continue
            explicit.setdefault(name,[]).append((int(first,16),int(last,16)))
    all_explicit=merge_ranges([r for ranges in explicit.values() for r in ranges])
    names=sorted(set(aliases.values()) | set(explicit))
    entries=[]
    blob=bytearray()
    for name in names:
        base=list(group_ranges.get(name,[]))
        if name in ('Common','Inherited'):
            base=subtract_ranges(base,all_explicit)
        ranges=merge_ranges(base+explicit.get(name,[]))
        if not ranges: continue
        offset=len(blob)
        blob.extend(b''.join(struct.pack('<II',a,b) for a,b in ranges))
        entries.append((name,offset,len(ranges)))
        code=codes.get(name)
        if code is not None and code!=name:
            entries.append((code,offset,len(ranges)))
    entries.sort()
    source=('// Generated by tools/codegen/generate.py from Unicode '+UNICODE_VERSION+'.\n'
            'pub const entries = [_]@import("../unicode.zig").Entry{\n'+
            '\n'.join(f'    .{{ .name = "{name}", .offset = {offset}, .count = {count} }},' for name,offset,count in entries)+
            '\n};\n')
    return {'script_extensions.bin':bytes(blob),'script_extensions.zig':source.encode()}, {'script_extensions':len(names),'script_extension_ranges':len(blob)//8}

