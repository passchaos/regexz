def unicode_char_names(unicode_files):
    text=unicode_files['UnicodeData.txt'].decode()
    entries=[]
    seen=set()
    for line in text.splitlines():
        parts=line.split(';')
        if len(parts)<2: continue
        name=parts[1]
        if not name or name.startswith('<'): continue
        normalized=''.join(ch for ch in name.upper() if ch not in ' -_')
        if not normalized or normalized in seen: continue
        seen.add(normalized)
        entries.append((normalized,int(parts[0],16)))
    entries.sort()
    index=bytearray()
    names=bytearray()
    for name,cp in entries:
        index.extend(struct.pack('<IHI',len(names),len(name),cp))
        names.extend(name.encode())
    blob=struct.pack('<I',len(entries))+bytes(index)+bytes(names)
    return {'char_names.bin':blob}, {'char_names':len(entries)}

def subtract_ranges(base, cut):
    out=[]
    j=0
    for a,b in base:
        start=a
        while j<len(cut) and cut[j][1]<start: j+=1
        k=j
        while k<len(cut) and cut[k][0]<=b:
            if cut[k][0]>start: out.append((start,cut[k][0]-1))
            if cut[k][1]>=b:
                start=b+1
                break
            start=cut[k][1]+1
            k+=1
        if start<=b: out.append((start,b))
    return out

