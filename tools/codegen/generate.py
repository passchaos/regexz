def parse_unicode_ranges(text, field_index=1, wanted=None):
    out=[]
    for line in text.splitlines():
        line=line.split('#',1)[0].strip()
        if not line: continue
        parts=[p.strip() for p in line.split(';')]
        if len(parts)<=field_index: continue
        prop=parts[field_index]
        if wanted is not None and prop!=wanted: continue
        rng=parts[0]
        if '..' in rng:
            first,last=rng.split('..')
        else:
            first=last=rng
        out.append((int(first,16),int(last,16),prop))
    out.sort()
    for (a1,b1,_),(a2,b2,_) in zip(out,out[1:]):
        assert b1<a2, (hex(b1),hex(a2))
    return out

