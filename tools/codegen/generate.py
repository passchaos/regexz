def fetch(url, timeout=90, attempts=3):
    last=None
    for _ in range(attempts):
        try:
            return urllib.request.urlopen(url, timeout=timeout).read()
        except Exception as error:
            last=error
    raise last

def unicode_case_mappings(unicode_files):
    text=unicode_files['UnicodeData.txt'].decode()
    upper={}
    lower={}
    for line in text.splitlines():
        parts=line.split(';')
        if len(parts)<15 or parts[1].startswith('<'): continue
        cp=int(parts[0],16)
        if parts[12]: upper[cp]=int(parts[12],16)
        if parts[13]: lower[cp]=int(parts[13],16)
    def compress(mapping):
        ranges=[]
        for cp,mapped in sorted(mapping.items()):
            delta=mapped-cp
            if ranges and cp==ranges[-1][1]+1 and delta==ranges[-1][2]:
                ranges[-1]=(ranges[-1][0],cp,delta)
            else:
                ranges.append((cp,cp,delta))
        return ranges
    upper_ranges=compress(upper)
    lower_ranges=compress(lower)
    def blob(ranges):
        return b''.join(struct.pack('<IIi',a,b,delta) for a,b,delta in ranges)
    return {'upper.bin':blob(upper_ranges),'lower.bin':blob(lower_ranges)}, {
        'upper_ranges':len(upper_ranges),'lower_ranges':len(lower_ranges),
        'case_mappings':len(upper)+len(lower)}


