#!/usr/bin/env python3
"""Generate static sorted unions of common Unicode property groups.

The checked-in ``groups.bin``/``groups.zig`` tables are already sorted and
non-overlapping per group.  Tokenizer classes such as ``[\\p{L}\\p{M}]``
normalize the concatenation of several groups at compile time; this script
precomputes the merged union so the parser can use a ready-to-use table
instead of sorting it again.

The unions are emitted as Zig ``Range`` arrays (not a packed binary blob) so
a class made only of the union can reference the table without copying it.

Run from the repository root:

    python3 tools/codegen/unions.py
"""
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
UNICODE = ROOT / "src/regex/unicode"
GROUPS_ZIG = UNICODE / "groups.zig"
GROUPS_BIN = UNICODE / "groups.bin"
UNIONS_ZIG = UNICODE / "unions.zig"

# Common class unions, in the exact names used by the parser.  The runtime
# lookup is order-insensitive.
UNIONS = [
    ("L", "M"),
    ("L", "N"),
    ("L", "M", "N"),
]

ENTRY_RE = re.compile(
    r'\.\{ \.name = "([^"]+)", \.offset = (\d+), \.count = (\d+) \}'
)


def load_groups():
    entries = {}
    for name, offset, count in ENTRY_RE.findall(GROUPS_ZIG.read_text()):
        entries[name] = (int(offset), int(count))
    return entries, GROUPS_BIN.read_bytes()


def ranges_of(groups, data, name):
    offset, count = groups[name]
    out = []
    for index in range(count):
        first, last = struct.unpack_from("<II", data, offset + index * 8)
        out.append((first, last))
    return out


def merged_union(groups, data, names):
    ranges = []
    for name in names:
        ranges.extend(ranges_of(groups, data, name))
    ranges.sort()
    merged = []
    for first, last in ranges:
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def array_name(names):
    return "ranges_" + "_".join(name.lower() for name in names)


def main():
    groups, data = load_groups()
    lines = [
        "// Generated by tools/codegen/generate.py from Unicode 17.0.0.",
        'const Range = @import("../unicode.zig").Range;',
        "",
    ]
    entries = []
    for names in UNIONS:
        merged = merged_union(groups, data, names)
        entries.append((names, array_name(names), len(merged)))
        lines.append(f"pub const {array_name(names)} = [_]Range{{")
        for first, last in merged:
            lines.append(f"    .{{ .first = 0x{first:x}, .last = 0x{last:x} }},")
        lines.append("};")
        lines.append("")
    lines.append('pub const entries = [_]@import("../unicode.zig").UnionEntry{')
    for names, array, _ in entries:
        name_list = ", ".join(f'"{name}"' for name in names)
        lines.append(f"    .{{ .names = &.{{ {name_list} }}, .ranges = &{array} }},")
    lines.append("};")
    lines.append("")
    UNIONS_ZIG.write_text("\n".join(lines))
    total = sum(count for _, _, count in entries)
    print(
        "wrote",
        UNIONS_ZIG.relative_to(ROOT),
        f"({len(entries)} unions, {total} ranges)",
    )


if __name__ == "__main__":
    main()
